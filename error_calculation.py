#error calculating functions
def reorder_velocities(velocities):
    return [
        velocities[8], velocities[1], velocities[6], velocities[2],
        velocities[7], velocities[3], velocities[5], velocities[0],
        velocities[4], velocities[9],
    ]


def calculate_rmse(predicted, measured, stations):
    predicted = predicted[:]
    measured = measured[:]

    for station in stations:
        predicted[station - 1] = 0
        measured[station - 1] = 0

    mse = sum((meas - pred) ** 2 for meas, pred in zip(measured, predicted)) / (len(measured) - len(stations))
    return math.sqrt(mse)


def error_for_month(velocities, stations, measured_values, month):
    if len(velocities) != 10:
        print("Needs 10-valued input")
        return

    predicted = reorder_velocities(velocities)
    rmse = calculate_rmse(predicted, measured_values, stations)
    print("Stations", stations, f"({month}):", rmse)
    return rmse


