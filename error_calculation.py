#plotting function
def bar_chart(names, values, 
              title = 'title', 
              x_label = 'x_label', 
              y_label = 'y_label', 
              color = 'purple', 
              ylim = None):
    """
    Creates a bar chart given two lists: model names and corresponding RMSEs
    """

    #length error check
    if len(names) != len(values):
        raise ValueError("Names and values lists must have the same length.")
    
    #bar chart
    plt.figure()
    plt.bar(names, values, width=0.75, color=color)
    plt.xlabel(x_label, fontsize=13)
    plt.ylabel(y_label, fontsize=13)
    plt.title(title, fontsize=16)
    plt.xticks(rotation=45, ha='right', fontsize=7.5)
    plt.ylim(top=ylim)

    #add labels on top of bars
    for i in range(len(names)):
        plt.text(i, values[i], f"{values[i]:.2f}",ha='center', va='bottom', fontsize=9)

    plt.tight_layout()
    plt.show()



def evaluate_combinations(data, combinations, error_func):
    errors = [error_func(values, combination) for values, combination in zip(data, combinations)]
    ranked = sorted(zip(errors, combinations), key=lambda item: item[0])
    return [item[0] for item in ranked], [list(item[1]) for item in ranked], [str(item[1]) for item in ranked]


